export function createAnnotationModule(core) {
  var state = core.state;
  var C     = core.C;

  /* ── tag list ──────────────────────────────────────────────── */
  // Rebuild the sidebar tag list from core.ANNOTATIONS.
  function buildList() {
    var list = document.getElementById('dp-annotation-list');
    if (!list) return;
    list.innerHTML = '';
    if (!core.ANNOTATIONS.length) {
      list.innerHTML = '<div id="dp-annotation-empty">No tags yet. Drag to create one.</div>'; return;
    }
    core.ANNOTATIONS.forEach(function(t) {
      var item = document.createElement('div');
      item.className = 'dp-annotation-item'; item.dataset.tagId = t.id;
      var title = document.createElement('div'); title.textContent = t.label; item.appendChild(title);
      if (t.subcomponents && t.subcomponents.length) {
        var sub = document.createElement('div'); sub.className = 'dp-annotation-item-sub';
        sub.textContent = t.subcomponents.map(function(s) { return s.label + ': ' + s.text; }).join(' · ');
        item.appendChild(sub);
      }
      item.addEventListener('click', function() { tagOpenExisting(t); });
      list.appendChild(item);
    });
  }

  /* ── tag overlays ──────────────────────────────────────────── */
  // Draw .dp-annotation-overlay divs for each tag in draw mode (outside of labeling phase).
  function renderAnnotationOverlays() {
    var viewer = document.getElementById('dp-viewer');
    if (!viewer) return;
    viewer.querySelectorAll('.dp-annotation-overlay').forEach(function(el) { el.remove(); });
    var scale = core.getScale();
    core.ANNOTATIONS.forEach(function(t) {
      var div = document.createElement('div');
      div.className = 'dp-annotation-overlay' + (t.autogenerated ? ' autogenerated' : '');
      div.dataset.tagId = t.id;
      div.style.left   = Math.round(t.bbox_left   * scale) + 'px';
      div.style.top    = Math.round(t.bbox_top    * scale) + 'px';
      div.style.width  = Math.round(t.bbox_width  * scale) + 'px';
      div.style.height = Math.round(t.bbox_height * scale) + 'px';
      div.title = t.label + ' (click to edit)';
      var lbl = document.createElement('div'); lbl.className = 'dp-annotation-overlay-label'; lbl.textContent = t.label;
      div.appendChild(lbl); viewer.appendChild(div);
    });
  }

  /* ── open existing ─────────────────────────────────────────── */
  // Load an existing tag into pending state and enter labeling mode.
  function tagOpenExisting(tag) {
    state.annotationEditingId      = tag.id;
    state.annotationPendingLabel   = tag.label;
    state.annotationPendingSubcomps = tag.subcomponents ? tag.subcomponents.slice() : [];
    state.annotationPendingBbox    = { left: tag.bbox_left, top: tag.bbox_top, width: tag.bbox_width, height: tag.bbox_height };
    tagEnterLabelingMode();
    document.getElementById('dp-annotation-delete-btn').style.display = '';
  }

  /* ── labeling mode ─────────────────────────────────────────── */
  // Switch the tag panel to labeling mode, optionally pre-filling NER suggestions.
  function tagEnterLabelingMode() {
    state.annotationPhase = 'labeling';
    state.annotationSubSelectedIds.clear();
    if (!state.annotationEditingId && state.annotationPendingBbox && core.nerSuggestSubcomps) {
      core.nerSuggestSubcomps(state.annotationPendingBbox);
      tagUpdateSubcompDisplay();
    }
    document.getElementById('dp-annotation-list-view').style.display = 'none';
    document.getElementById('dp-annotation-label-view').style.display = 'flex';
    document.getElementById('dp-annotation-label-heading').textContent = state.annotationEditingId ? 'Edit tag' : 'New tag';
    var labelInput = document.getElementById('dp-annotation-label-input');
    labelInput.value = state.annotationPendingLabel;
    document.getElementById('dp-annotation-delete-btn').style.display = 'none';
    document.getElementById('dp-annotation-sub-input-row').style.display = 'none';
    tagUpdateSubcompDisplay();
    updateVeils();
    core.renderOverlays();
    labelInput.focus(); labelInput.select();
  }

  // Reset all pending tag state and return to draw mode.
  function tagExitLabelingMode() {
    state.annotationPhase = 'draw'; state.annotationEditingId = null; state.annotationPendingLabel = '';
    state.annotationPendingSubcomps = []; state.annotationPendingBbox = null;
    state.annotationSubSelectedIds.clear(); state.annotationSubDrawStart = null;
    state.isDragging = false; state.annotationResizing = null;
    // Discard in-session subcomp/bbox undo entries — they belong to this pending tag only.
    var isTransient = function(e) { return e.type === 'annotation-subcomp-change' || e.type === 'annotation-bbox-change'; };
    state.undoStack = state.undoStack.filter(function(e) { return !isTransient(e); });
    state.redoStack = state.redoStack.filter(function(e) { return !isTransient(e); });
    document.getElementById('dp-annotation-label-view').style.display = 'none';
    document.getElementById('dp-annotation-list-view').style.display = '';
    document.getElementById('dp-annotation-sub-input-row').style.display = 'none';
    document.getElementById('dp-annotation-active-rect').style.display = 'none';
    document.getElementById('dp-annotation-sub-rect').style.display = 'none';
    ['dp-veil-top','dp-veil-bottom','dp-veil-left','dp-veil-right'].forEach(function(id) {
      document.getElementById(id).style.display = 'none';
    });
    buildList(); core.renderOverlays(); core.updateBadge();
  }

  // Deep-copy subcomps array (each element is a plain object with scalar fields).
  function _cloneSubcomps(arr) { return arr.map(function(s) { return Object.assign({}, s); }); }

  // Snapshot current subcomps, mutate via fn(), then record an undo entry for the change.
  function _withSubcompUndo(fn) {
    var prev = _cloneSubcomps(state.annotationPendingSubcomps);
    fn();
    core.recordUndo({ type: 'annotation-subcomp-change', prev: prev, next: _cloneSubcomps(state.annotationPendingSubcomps) });
  }

  /* ── veils ─────────────────────────────────────────────────── */
  // Reposition the four veil overlays and the active-rect border around tagPendingBbox.
  function updateVeils() {
    if (!state.annotationPendingBbox) return;
    var viewer = document.getElementById('dp-viewer'), scale = core.getScale();
    var bx = Math.round(state.annotationPendingBbox.left   * scale);
    var by = Math.round(state.annotationPendingBbox.top    * scale);
    var bw = Math.round(state.annotationPendingBbox.width  * scale);
    var bh = Math.round(state.annotationPendingBbox.height * scale);
    var vw = viewer.offsetWidth, vh = viewer.offsetHeight;
    function setVeil(id, l, t, w, h) {
      var el = document.getElementById(id);
      el.style.left = l+'px'; el.style.top = t+'px'; el.style.width = w+'px'; el.style.height = h+'px';
      el.style.display = (w > 0 && h > 0) ? '' : 'none';
    }
    setVeil('dp-veil-top',    0,     0,     vw,    by);
    setVeil('dp-veil-bottom', 0,     by+bh, vw,    Math.max(0, vh - by - bh));
    setVeil('dp-veil-left',   0,     by,    bx,    bh);
    setVeil('dp-veil-right',  bx+bw, by,    Math.max(0, vw - bx - bw), bh);
    var ar = document.getElementById('dp-annotation-active-rect');
    ar.style.left = bx+'px'; ar.style.top = by+'px'; ar.style.width = bw+'px'; ar.style.height = bh+'px';
    ar.style.display = 'block';
  }

  /* ── subcomp display ───────────────────────────────────────── */
  // Rebuild the subcomponent list in the panel from state.annotationPendingSubcomps.
  function tagUpdateSubcompDisplay() {
    var list = document.getElementById('dp-annotation-subcomp-list');
    list.innerHTML = '';
    var firstSelected = null;
    state.annotationPendingSubcomps.forEach(function(sc, i) {
      var isSelected = state.annotationSubSelectedIds.has(sc.word_id);
      var row = document.createElement('div');
      row.className = 'dp-subcomp-row' + (isSelected ? ' highlighted' : '');
      var lbl = document.createElement('span'); lbl.className = 'dp-subcomp-label'; lbl.textContent = sc.label + ':';
      var txt = document.createElement('span'); txt.className = 'dp-subcomp-text';  txt.textContent = sc.text;
      var rm  = document.createElement('span'); rm.className  = 'dp-subcomp-rm';    rm.textContent  = '×'; rm.title = 'Remove from pattern';
      (function(idx) { rm.addEventListener('click', function(e) {
        e.stopPropagation();
        _withSubcompUndo(function() {
          state.annotationSubSelectedIds.delete(state.annotationPendingSubcomps[idx].word_id);
          state.annotationPendingSubcomps.splice(idx, 1);
        });
        tagMaybeShowSubInput(); tagUpdateSubcompDisplay(); core.renderOverlays();
      }); })(i);
      (function(wid) { row.addEventListener('click', function(e) {
        if (e.target.classList.contains('dp-subcomp-rm')) return;
        if (state.annotationSubSelectedIds.has(wid)) state.annotationSubSelectedIds.delete(wid); else state.annotationSubSelectedIds.add(wid);
        tagMaybeShowSubInput(); tagUpdateSubcompDisplay(); core.renderOverlays();
      }); })(sc.word_id);
      row.appendChild(lbl); row.appendChild(txt); row.appendChild(rm);
      list.appendChild(row);
      if (isSelected && !firstSelected) firstSelected = row;
    });
    if (firstSelected) firstSelected.scrollIntoView({ block: 'nearest', behavior: 'smooth' });
    core.renderOverlays();
  }

  /* ── ditto helpers ─────────────────────────────────────────── */
  // Return true if the text consists entirely of ditto-mark characters.
  function isDitto(text) {
    var t = text.trim();
    return /^["'«»''""″〃〞＂]+$/.test(t) || t === '""' || t === "''" || t === '``';
  }

  // Find the nearest preceding tag with the given subcomponent label and return its non-ditto text.
  function resolveDitto(label, currentTop) {
    var candidates = core.ANNOTATIONS.filter(function(t) { return t.bbox_top + t.bbox_height <= currentTop + 8; });
    candidates.sort(function(a, b) { return b.bbox_top - a.bbox_top; });
    for (var i = 0; i < candidates.length; i++) {
      var sc = (candidates[i].subcomponents || []).find(function(s) { return s.label === label; });
      if (sc && sc.text && !isDitto(sc.text)) return sc.text;
    }
    return null;
  }

  /* ── sub-label ─────────────────────────────────────────────── */
  // Assign label to all currently selected sub-words, resolving dittos where needed.
  function tagConfirmSubLabel(label) {
    label = label.trim();
    if (!label || !state.annotationSubSelectedIds.size) return;
    _withSubcompUndo(function() {
      state.annotationSubSelectedIds.forEach(function(wid) {
        var w = core.wordById[wid]; if (!w) return;
        var existing = state.annotationPendingSubcomps.find(function(s) { return s.word_id === wid; });
        if (existing) { existing.label = label; }
        else {
          var text = w.text || '';
          if (isDitto(text) && state.annotationPendingBbox) { var resolved = resolveDitto(label, state.annotationPendingBbox.top); if (resolved) text = resolved; }
          state.annotationPendingSubcomps.push({ word_id: wid, label: label, text: text });
        }
      });
    });
    state.annotationSubSelectedIds.clear();
    document.getElementById('dp-annotation-sub-input').value = '';
    document.getElementById('dp-annotation-sub-input-row').style.display = 'none';
    tagUpdateSubcompDisplay(); populateLabelDatalist();
  }

  // Return the shared label of all selected sub-words, or '' if they differ.
  function _commonSelectedLabel() {
    var seen = null, all = true;
    state.annotationSubSelectedIds.forEach(function(wid) {
      var sc = state.annotationPendingSubcomps.find(function(s) { return s.word_id === wid; });
      if (!sc) { all = false; return; }
      if (seen === null) seen = sc.label; else if (seen !== sc.label) all = false;
    });
    return (all && seen !== null) ? seen : '';
  }

  // Show the sub-label input row when words are selected, hide it when the selection is empty.
  function tagMaybeShowSubInput() {
    var row = document.getElementById('dp-annotation-sub-input-row');
    if (state.annotationSubSelectedIds.size > 0) {
      document.getElementById('dp-annotation-sub-input').value = _commonSelectedLabel();
      row.style.display = '';
    } else { document.getElementById('dp-annotation-sub-input').value = ''; row.style.display = 'none'; }
    core.renderOverlays();
  }

  /* ── sub-word selection ────────────────────────────────────── */
  // Toggle selection of a single sub-word by id, ignoring clicks outside the pending bbox.
  function tagSubWordClick(wordId, shiftKey) {
    if (!state.annotationPendingBbox) return;
    var w = core.wordById[wordId]; if (!w) return;
    if (w.left < state.annotationPendingBbox.left || w.top < state.annotationPendingBbox.top ||
        w.left + w.width > state.annotationPendingBbox.left + state.annotationPendingBbox.width + 4 ||
        w.top + w.height > state.annotationPendingBbox.top  + state.annotationPendingBbox.height + 4) return;
    if (!shiftKey) state.annotationSubSelectedIds.clear();
    if (state.annotationSubSelectedIds.has(wordId)) state.annotationSubSelectedIds.delete(wordId); else state.annotationSubSelectedIds.add(wordId);
    tagMaybeShowSubInput(); tagUpdateSubcompDisplay();
  }

  // Select sub-words inside the given viewer-local rect that also lie within the pending bbox.
  function tagSubSelectInRect(x1, y1, x2, y2, shiftKey) {
    if (!state.annotationPendingBbox) return;
    if (!shiftKey) state.annotationSubSelectedIds.clear();
    var scale = core.getScale(), px1 = x1/scale, py1 = y1/scale, px2 = x2/scale, py2 = y2/scale;
    var rb = state.annotationPendingBbox;
    core.OCR_WORDS.forEach(function(w) {
      if ((w.left+w.width) > px1 && w.left < px2 && (w.top+w.height) > py1 && w.top < py2 &&
          w.left >= rb.left - 4 && w.top >= rb.top - 4 &&
          w.left + w.width <= rb.left + rb.width + 4 && w.top + w.height <= rb.top + rb.height + 4)
        state.annotationSubSelectedIds.add(w.id);
    });
    tagMaybeShowSubInput(); tagUpdateSubcompDisplay();
  }

  /* ── datalist ──────────────────────────────────────────────── */
  // Populate the sub-label autocomplete datalist from all existing tags and pending subcomps.
  function populateLabelDatalist() {
    var dl = document.getElementById('dp-sub-label-list'); if (!dl) return;
    var seen = {};
    core.ANNOTATIONS.forEach(function(t) { (t.subcomponents || []).forEach(function(sc) { if (sc.label) seen[sc.label] = true; }); });
    state.annotationPendingSubcomps.forEach(function(sc) { if (sc.label) seen[sc.label] = true; });
    dl.innerHTML = '';
    Object.keys(seen).sort().forEach(function(lbl) { var opt = document.createElement('option'); opt.value = lbl; dl.appendChild(opt); });
  }

  /* ── undo / redo helpers ────────────────────────────────────── */
  // POST delete for id, remove from TAGS, and update doc count.
  function _deleteTagById(id) {
    core.postJson(C.annotationDeleteUrl, 'annotation_id=' + id).then(function(data) {
      if (!data.ok) return;
      core.ANNOTATIONS = core.ANNOTATIONS.filter(function(t) { return t.id !== id; });
      adjustDocAnnotationCount(-1); buildList(); core.renderOverlays(); core.updateBadge();
    });
  }

  // POST update using a full tag snapshot (used for undo/redo).
  function _updateTagFromSnapshot(tagData) {
    var subcomps = tagData.subcomponents || [];
    var body = 'annotation_id=' + tagData.id + '&label=' + encodeURIComponent(tagData.label) +
               '&bbox_left=' + tagData.bbox_left + '&bbox_top=' + tagData.bbox_top +
               '&bbox_width=' + tagData.bbox_width + '&bbox_height=' + tagData.bbox_height +
               '&subcomponents=' + encodeURIComponent(JSON.stringify(subcomps));
    core.postJson(C.annotationUpdateUrl, body).then(function(data) {
      if (!data.ok) return;
      var idx = core.ANNOTATIONS.findIndex(function(t) { return t.id === data.annotation.id; });
      if (idx >= 0) core.ANNOTATIONS[idx] = data.annotation;
      buildList(); core.renderOverlays();
    });
  }

  // POST create using snapshot data, add to TAGS, and update doc count (used for undo/redo).
  function _createTagFromSnapshot(tagData, cb) {
    var subcomps = tagData.subcomponents || [];
    var body = 'source_type_id=' + C.annotationSourceTypeId + '&source_id=' + C.annotationSourceId +
               '&label=' + encodeURIComponent(tagData.label) +
               '&bbox_left=' + tagData.bbox_left + '&bbox_top=' + tagData.bbox_top +
               '&bbox_width=' + tagData.bbox_width + '&bbox_height=' + tagData.bbox_height +
               '&subcomponents=' + encodeURIComponent(JSON.stringify(subcomps));
    core.postJson(C.annotationCreateUrl, body).then(function(data) {
      if (!data.ok) return;
      core.ANNOTATIONS.push(data.annotation); adjustDocAnnotationCount(1);
      buildList(); core.renderOverlays(); core.updateBadge();
      if (cb) cb(data.annotation);
    });
  }

  /* ── save / delete ─────────────────────────────────────────── */
  // POST create or update for the pending tag and exit labeling mode on success.
  function tagSave() {
    var label = document.getElementById('dp-annotation-label-input').value.trim();
    if (!label) { document.getElementById('dp-annotation-label-input').focus(); return; }
    if (!state.annotationPendingBbox) return;
    var subcomps = state.annotationPendingSubcomps.slice();
    var btn = document.getElementById('dp-annotation-save-btn'); btn.disabled = true; btn.textContent = 'Saving…';
    var isUpdate = !!state.annotationEditingId;
    var prevSnap = null;
    if (isUpdate) {
      var _pt = core.ANNOTATIONS.find(function(t) { return t.id === state.annotationEditingId; });
      if (_pt) { prevSnap = Object.assign({}, _pt); prevSnap.subcomponents = (_pt.subcomponents || []).slice(); }
    }
    var url, body;
    if (state.annotationEditingId) {
      url = C.annotationUpdateUrl;
      body = 'annotation_id=' + state.annotationEditingId + '&label=' + encodeURIComponent(label) +
             '&bbox_left=' + state.annotationPendingBbox.left + '&bbox_top=' + state.annotationPendingBbox.top +
             '&bbox_width=' + state.annotationPendingBbox.width + '&bbox_height=' + state.annotationPendingBbox.height +
             '&subcomponents=' + encodeURIComponent(JSON.stringify(subcomps));
    } else {
      url = C.annotationCreateUrl;
      body = 'source_type_id=' + C.annotationSourceTypeId + '&source_id=' + C.annotationSourceId +
             '&label=' + encodeURIComponent(label) +
             '&bbox_left=' + state.annotationPendingBbox.left + '&bbox_top=' + state.annotationPendingBbox.top +
             '&bbox_width=' + state.annotationPendingBbox.width + '&bbox_height=' + state.annotationPendingBbox.height +
             '&subcomponents=' + encodeURIComponent(JSON.stringify(subcomps));
    }
    core.postJson(url, body).then(function(data) {
      btn.disabled = false; btn.textContent = 'Save ↵';
      if (!data.ok) { alert(data.error || 'Error saving tag.'); return; }
      if (isUpdate) {
        var idx = core.ANNOTATIONS.findIndex(function(t) { return t.id === state.annotationEditingId; });
        if (idx >= 0) core.ANNOTATIONS[idx] = data.annotation;
        var nextSnap = Object.assign({}, data.annotation); nextSnap.subcomponents = (data.annotation.subcomponents || []).slice();
        core.recordUndo({ type: 'annotation-update', tagId: data.annotation.id, prev: prevSnap, next: nextSnap });
      } else {
        core.ANNOTATIONS.push(data.annotation); adjustDocAnnotationCount(1);
        core.recordUndo({ type: 'annotation-create', tagId: data.annotation.id });
      }
      populateLabelDatalist(); tagExitLabelingMode();
    }).catch(function() { btn.disabled = false; btn.textContent = 'Save ↵'; });
  }

  // POST delete for the current tag and remove it from core.ANNOTATIONS.
  function tagDelete() {
    if (!state.annotationEditingId) return;
    if (!confirm('Delete this tag?')) return;
    var _dt = core.ANNOTATIONS.find(function(t) { return t.id === state.annotationEditingId; });
    var snapCopy = _dt ? Object.assign({}, _dt, { subcomponents: (_dt.subcomponents || []).slice() }) : null;
    core.postJson(C.annotationDeleteUrl, 'annotation_id=' + state.annotationEditingId).then(function(data) {
      if (!data.ok) { alert('Error deleting tag.'); return; }
      var id = state.annotationEditingId;
      core.ANNOTATIONS = core.ANNOTATIONS.filter(function(t) { return t.id !== id; });
      adjustDocAnnotationCount(-1);
      if (snapCopy) core.recordUndo({ type: 'annotation-delete', tagData: snapCopy });
      tagExitLabelingMode();
    });
  }

  // Increment or decrement the document-level tag count badge.
  function adjustDocAnnotationCount(delta) {
    var el = document.getElementById('dp-doc-annotation-count-val'); if (!el) return;
    var n = (parseInt(el.textContent, 10) || 0) + delta; el.textContent = n;
    var suffix = document.getElementById('dp-doc-annotation-count-suffix');
    if (suffix) suffix.textContent = 'tag' + (n === 1 ? '' : 's');
  }

  /* ── render ────────────────────────────────────────────────── */
  // In labeling phase: render ghost word overlays inside the bbox; otherwise render tag overlays.
  function render(viewer, scale) {
    if (state.annotationPhase === 'labeling') {
      var taggedIds = new Set(state.annotationPendingSubcomps.map(function(s) { return s.word_id; }));
      core.OCR_WORDS.forEach(function(w) {
        if (state.annotationPendingBbox) {
          var rb = state.annotationPendingBbox;
          if (w.left < rb.left - 4 || w.top < rb.top - 4 ||
              w.left + w.width  > rb.left + rb.width  + 4 ||
              w.top  + w.height > rb.top  + rb.height + 4) return;
        }
        var div = document.createElement('div');
        var cls = 'dp-word-ghost';
        if (state.annotationSubSelectedIds.has(w.id)) cls += ' sub-selected';
        else if (taggedIds.has(w.id)) cls += ' sub-tagged';
        div.className    = cls; div.dataset.wordId = w.id;
        div.style.left   = Math.round(w.left   * scale) + 'px';
        div.style.top    = Math.round(w.top    * scale) + 'px';
        div.style.width  = Math.round(w.width  * scale) + 'px';
        div.style.height = Math.round(w.height * scale) + 'px';
        div.title = w.text;
        viewer.appendChild(div);
      });
    } else {
      renderAnnotationOverlays();
    }
  }

  /* ── mouse handlers ────────────────────────────────────────── */
  // Begin a tag draw gesture or a sub-word selection gesture.
  function onMousedown(e) {
    if (state.annotationPhase === 'draw') {
      e.preventDefault(); state.annotationDrawStart = { x: e.clientX, y: e.clientY }; state.isDragging = false;
    } else if (state.annotationPhase === 'labeling') {
      var ghostEl = e.target.closest ? e.target.closest('.dp-word-ghost') : null;
      if (!ghostEl) { e.preventDefault(); state.annotationSubDrawStart = { x: e.clientX, y: e.clientY }; state.isDragging = false; }
    }
  }

  // Handle corner-resize drag, tag draw rubber-band, or sub-word selection rubber-band.
  function onMousemove(e) {
    if (state.annotationResizing) {
      var scale = core.getScale();
      var dx = (e.clientX - state.annotationResizing.startX) / scale;
      var dy = (e.clientY - state.annotationResizing.startY) / scale;
      var b  = state.annotationResizing.startBbox;
      var nb = { left: b.left, top: b.top, width: b.width, height: b.height };
      var MIN = 10;
      switch (state.annotationResizing.corner) {
        case 'tl': nb.left = Math.round(b.left+dx); nb.top = Math.round(b.top+dy); nb.width = Math.max(MIN, Math.round(b.width-dx)); nb.height = Math.max(MIN, Math.round(b.height-dy)); if (nb.width===MIN) nb.left=b.left+b.width-MIN; if (nb.height===MIN) nb.top=b.top+b.height-MIN; break;
        case 'tr': nb.top = Math.round(b.top+dy); nb.width = Math.max(MIN, Math.round(b.width+dx)); nb.height = Math.max(MIN, Math.round(b.height-dy)); if (nb.height===MIN) nb.top=b.top+b.height-MIN; break;
        case 'bl': nb.left = Math.round(b.left+dx); nb.width = Math.max(MIN, Math.round(b.width-dx)); nb.height = Math.max(MIN, Math.round(b.height+dy)); if (nb.width===MIN) nb.left=b.left+b.width-MIN; break;
        case 'br': nb.width = Math.max(MIN, Math.round(b.width+dx)); nb.height = Math.max(MIN, Math.round(b.height+dy)); break;
      }
      state.annotationPendingBbox = nb; updateVeils(); core.renderOverlays(); return;
    }
    if (state.annotationPhase === 'draw' && state.annotationDrawStart) {
      var dx2 = e.clientX - state.annotationDrawStart.x, dy2 = e.clientY - state.annotationDrawStart.y;
      if (!state.isDragging && Math.sqrt(dx2*dx2 + dy2*dy2) > 5) state.isDragging = true;
      if (state.isDragging) {
        var vr = document.getElementById('dp-viewer').getBoundingClientRect();
        var dr = document.getElementById('dp-annotation-draw-rect');
        core.updateRubberBand(dr, state.annotationDrawStart.x, state.annotationDrawStart.y, e.clientX, e.clientY, vr);
      }
    } else if (state.annotationPhase === 'labeling' && state.annotationSubDrawStart) {
      var dx3 = e.clientX - state.annotationSubDrawStart.x, dy3 = e.clientY - state.annotationSubDrawStart.y;
      if (!state.isDragging && Math.sqrt(dx3*dx3 + dy3*dy3) > 5) state.isDragging = true;
      if (state.isDragging) {
        var vr2 = document.getElementById('dp-viewer').getBoundingClientRect();
        var sr  = document.getElementById('dp-annotation-sub-rect');
        core.updateRubberBand(sr, state.annotationSubDrawStart.x, state.annotationSubDrawStart.y, e.clientX, e.clientY, vr2);
      }
    }
  }

  // Finalise a draw, resize, or sub-selection gesture; open an existing tag on single click.
  function onMouseup(e) {
    if (state.annotationResizing) {
      var prevBbox = state.annotationResizing.startBbox, nextBbox = Object.assign({}, state.annotationPendingBbox);
      if (JSON.stringify(prevBbox) !== JSON.stringify(nextBbox))
        core.recordUndo({ type: 'annotation-bbox-change', prev: prevBbox, next: nextBbox });
      state.annotationResizing = null; return;
    }
    if (state.annotationPhase === 'draw') {
      document.getElementById('dp-annotation-draw-rect').style.display = 'none';
      if (state.isDragging && state.annotationDrawStart) {
        var vr = document.getElementById('dp-viewer').getBoundingClientRect(), scale = core.getScale();
        var px = Math.min(state.annotationDrawStart.x, e.clientX) - vr.left;
        var py = Math.min(state.annotationDrawStart.y, e.clientY) - vr.top;
        var pw = Math.abs(e.clientX - state.annotationDrawStart.x), ph = Math.abs(e.clientY - state.annotationDrawStart.y);
        pw = Math.max(0, pw - Math.max(0, -px)); ph = Math.max(0, ph - Math.max(0, -py));
        px = Math.max(0, px); py = Math.max(0, py);
        if (pw > 4 && ph > 4) {
          state.annotationPendingBbox = { left: Math.round(px/scale), top: Math.round(py/scale), width: Math.round(pw/scale), height: Math.round(ph/scale) };
          state.annotationPendingLabel = ''; state.annotationPendingSubcomps = []; state.annotationEditingId = null;
          tagEnterLabelingMode();
        }
      } else if (!state.isDragging) {
        var nerEl = e.target.closest ? e.target.closest('.dp-ner-overlay') : null;
        if (nerEl && nerEl.dataset.wordIds) {
          if (core.nerOpenPopup) core.nerOpenPopup(nerEl.dataset.wordIds.split(',').map(Number));
        } else {
          var vrc = document.getElementById('dp-viewer').getBoundingClientRect(), sc = core.getScale();
          var cpx = (e.clientX - vrc.left) / sc, cpy = (e.clientY - vrc.top) / sc;
          var hit = core.ANNOTATIONS.find(function(t) { return cpx >= t.bbox_left && cpy >= t.bbox_top && cpx <= t.bbox_left+t.bbox_width && cpy <= t.bbox_top+t.bbox_height; });
          if (hit) tagOpenExisting(hit);
        }
      }
      state.annotationDrawStart = null; state.isDragging = false;
    } else if (state.annotationPhase === 'labeling') {
      document.getElementById('dp-annotation-sub-rect').style.display = 'none';
      if (state.isDragging && state.annotationSubDrawStart) {
        var vr4 = document.getElementById('dp-viewer').getBoundingClientRect();
        tagSubSelectInRect(
          Math.min(state.annotationSubDrawStart.x, e.clientX) - vr4.left, Math.min(state.annotationSubDrawStart.y, e.clientY) - vr4.top,
          Math.max(state.annotationSubDrawStart.x, e.clientX) - vr4.left, Math.max(state.annotationSubDrawStart.y, e.clientY) - vr4.top,
          e.shiftKey
        );
      } else if (!state.isDragging) {
        var ghostEl2 = e.target.closest ? e.target.closest('.dp-word-ghost') : null;
        if (ghostEl2 && ghostEl2.dataset.wordId) tagSubWordClick(parseInt(ghostEl2.dataset.wordId), e.shiftKey);
      }
      state.annotationSubDrawStart = null; state.isDragging = false;
    }
    e.stopPropagation();
  }

  /* ── keyboard ──────────────────────────────────────────────── */
  // Handle Enter (confirm sub-label or save), Escape (deselect or exit), Delete (remove subcomps).
  function onKeydown(e) {
    if (state.annotationPhase !== 'labeling') return;
    var subInput   = document.getElementById('dp-annotation-sub-input');
    var labelInput = document.getElementById('dp-annotation-label-input');
    var subActive  = subInput && subInput.parentElement.style.display !== 'none' && document.activeElement === subInput;
    if (e.key === 'Enter') {
      if (subActive) { e.preventDefault(); tagConfirmSubLabel(subInput.value); return; }
      if (document.activeElement === labelInput) { e.preventDefault(); labelInput.blur(); return; }
      e.preventDefault(); tagSave(); return;
    }
    if (e.key === 'Escape') {
      if (subActive) {
        e.preventDefault(); state.annotationSubSelectedIds.clear();
        document.getElementById('dp-annotation-sub-input-row').style.display = 'none'; core.renderOverlays(); return;
      }
      e.preventDefault(); tagExitLabelingMode(); return;
    }
    if ((e.key === 'Delete' || e.key === 'Backspace') && !subActive && document.activeElement !== labelInput && state.annotationSubSelectedIds.size > 0) {
      e.preventDefault();
      _withSubcompUndo(function() {
        state.annotationSubSelectedIds.forEach(function(wid) {
          var idx = state.annotationPendingSubcomps.findIndex(function(s) { return s.word_id === wid; });
          if (idx >= 0) state.annotationPendingSubcomps.splice(idx, 1);
        });
      });
      state.annotationSubSelectedIds.clear();
      document.getElementById('dp-annotation-sub-input-row').style.display = 'none';
      tagUpdateSubcompDisplay(); core.renderOverlays(); return;
    }
  }

  // Exit labeling mode (used by core when switching away from the label tab).
  function clearSelection() {
    if (state.annotationPhase === 'labeling') tagExitLabelingMode();
  }

  /* ── setup UI ──────────────────────────────────────────────── */
  // Attach tag panel button listeners and corner-resize handle listeners.
  function setupUI() {
    document.getElementById('dp-annotation-save-btn').addEventListener('click', function(e) { e.preventDefault(); tagSave(); });
    document.getElementById('dp-annotation-cancel-btn').addEventListener('click', function(e) { e.preventDefault(); tagExitLabelingMode(); });
    document.getElementById('dp-annotation-delete-btn').addEventListener('click', function(e) { e.preventDefault(); tagDelete(); });
    document.getElementById('dp-annotation-sub-clear-btn').addEventListener('click', function(e) {
      e.preventDefault();
      _withSubcompUndo(function() {
        state.annotationSubSelectedIds.forEach(function(wid) {
          var idx = state.annotationPendingSubcomps.findIndex(function(s) { return s.word_id === wid; });
          if (idx >= 0) state.annotationPendingSubcomps.splice(idx, 1);
        });
      });
      state.annotationSubSelectedIds.clear();
      document.getElementById('dp-annotation-sub-input').value = '';
      document.getElementById('dp-annotation-sub-input-row').style.display = 'none';
      tagUpdateSubcompDisplay(); core.renderOverlays();
    });

    document.querySelectorAll('.dp-annotation-corner').forEach(function(handle) {
      handle.addEventListener('mousedown', function(e) {
        if (state.annotationPhase !== 'labeling' || !state.annotationPendingBbox) return;
        e.preventDefault(); e.stopPropagation();
        state.annotationResizing = { corner: handle.dataset.corner, startX: e.clientX, startY: e.clientY, startBbox: Object.assign({}, state.annotationPendingBbox) };
      });
    });

    core.registerUndoHandler('annotation-create', function(e, pushInverse) {
      var snap = core.ANNOTATIONS.find(function(t) { return t.id === e.tagId; });
      if (!snap) return;
      pushInverse({ type: 'annotation-delete', tagData: Object.assign({}, snap, { subcomponents: (snap.subcomponents || []).slice() }) });
      if (state.annotationPhase === 'labeling') tagExitLabelingMode();
      _deleteTagById(e.tagId);
    });
    core.registerUndoHandler('annotation-subcomp-change', function(e, pushInverse) {
      pushInverse({ type: 'annotation-subcomp-change', prev: e.next, next: e.prev });
      state.annotationPendingSubcomps = _cloneSubcomps(e.prev);
      tagUpdateSubcompDisplay();
    });
    core.registerUndoHandler('annotation-bbox-change', function(e, pushInverse) {
      pushInverse({ type: 'annotation-bbox-change', prev: e.next, next: e.prev });
      state.annotationPendingBbox = Object.assign({}, e.prev);
      updateVeils(); core.renderOverlays();
    });
    core.registerUndoHandler('annotation-update', function(e, pushInverse) {
      if (!e.prev) return;
      pushInverse({ type: 'annotation-update', tagId: e.tagId, prev: e.next, next: e.prev });
      _updateTagFromSnapshot(e.prev);
    });
    core.registerUndoHandler('annotation-delete', function(e, pushInverse) {
      _createTagFromSnapshot(e.tagData, function(newTag) {
        pushInverse({ type: 'annotation-create', tagId: newTag.id });
      });
    });
  }

  return {
    render, onMousedown, onMousemove, onMouseup, onKeydown, setupUI,
    clearSelection, updateVeils,
    buildList, renderAnnotationOverlays, populateLabelDatalist,
  };
}
