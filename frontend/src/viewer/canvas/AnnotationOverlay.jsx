// Two modes:
//   - draw phase: render saved-annotation rectangles with click-to-edit.
//   - labeling phase: render ghost word boxes inside the pending bbox,
//     toggling selection / tagged classes.

import { useViewerState } from '../state/ViewerContext.jsx';

export default function AnnotationOverlay({ scale }) {
  const { annotations, annotation, words } = useViewerState();

  if (annotation.phase === 'labeling') {
    const taggedIds = new Set((annotation.pendingSubcomps || []).map((s) => s.word_id));
    return words.map((w) => {
      if (annotation.pendingBbox) {
        const rb = annotation.pendingBbox;
        if (
          w.left < rb.left - 4 ||
          w.top < rb.top - 4 ||
          w.left + w.width > rb.left + rb.width + 4 ||
          w.top + w.height > rb.top + rb.height + 4
        ) {
          return null;
        }
      }
      let cls = 'dp-word-ghost';
      if (annotation.subSelectedIds.has(w.id)) cls += ' sub-selected';
      else if (taggedIds.has(w.id)) cls += ' sub-tagged';
      return (
        <div
          key={w.id}
          className={cls}
          data-word-id={w.id}
          title={w.corrected_text || w.ocr_text || ''}
          style={{
            left: Math.round(w.left * scale) + 'px',
            top: Math.round(w.top * scale) + 'px',
            width: Math.round(w.width * scale) + 'px',
            height: Math.round(w.height * scale) + 'px',
          }}
        />
      );
    });
  }

  return annotations.map((t) => (
    <div
      key={t.id}
      className={'dp-annotation-overlay' + (t.autogenerated ? ' autogenerated' : '')}
      data-tag-id={t.id}
      title={t.label + ' (click to edit)'}
      style={{
        left: Math.round(t.bbox_left * scale) + 'px',
        top: Math.round(t.bbox_top * scale) + 'px',
        width: Math.round(t.bbox_width * scale) + 'px',
        height: Math.round(t.bbox_height * scale) + 'px',
      }}
    >
      <div className="dp-annotation-overlay-label">{t.label}</div>
    </div>
  ));
}
